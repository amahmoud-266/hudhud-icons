#!/usr/bin/env python3
"""
build_hudhud_style.py
---------------------
Builds styles/Hudhud.mapcss with ALL icons embedded inside the file
(small base64 PNGs), so JOSM never downloads any image -> fast loading.

Inputs (repo root):
  Hudhud.template.mapcss   meta + original rules + Style settings.
                           {{img:<path>}} or {{img:<path>:<px>}} is replaced
                           by an embedded image.
  AI/ and Basic/           every image named <key>=<value>.png becomes a rule:
                           any node with that tag shows the image
                           (e.g. QC=Done.png, sign_type=highway=stop.png)
  Basic/unKnown.png        icon for a sign_type value that has no image

Usage:   python3 tools/build_hudhud_style.py            (from repo root)
Needs:   pip install pillow
"""
import base64, io, os, re, sys
from PIL import Image

ROOT = sys.argv[1] if len(sys.argv) > 1 else '.'
OUT = os.path.join(ROOT, 'styles', 'Hudhud.mapcss')
TEMPLATE = os.path.join(ROOT, 'Hudhud.template.mapcss')
SIGNS_DIR = os.path.join(ROOT, 'AI')
UNKNOWN = os.path.join(ROOT, 'Basic', 'unKnown.png')
PX = 64                      # embedded size (largest icon-size setting is 60)
EXTS = ('.png', '.jpg', '.jpeg', '.webp')

_cache = {}


def data_uri(path, px=PX):
    key = (path, px)
    if key in _cache:
        return _cache[key]
    im = Image.open(path).convert('RGBA')
    bbox = im.getchannel('A').getbbox()          # trim empty transparent border
    if bbox:
        im = im.crop(bbox)
    side = max(im.size)                          # pad to square, keep aspect
    sq = Image.new('RGBA', (side, side), (0, 0, 0, 0))
    sq.paste(im, ((side - im.size[0]) // 2, (side - im.size[1]) // 2))
    sq = sq.resize((px, px), Image.LANCZOS)
    sq = sq.quantize(128, method=Image.Quantize.FASTOCTREE)   # ~3.5x smaller, same look
    buf = io.BytesIO()
    sq.save(buf, 'PNG', optimize=True)
    uri = 'data:image/png;base64,' + base64.b64encode(buf.getvalue()).decode()
    _cache[key] = uri
    return uri


def regex_escape(v):
    return re.sub(r'([\\.^$|?*+()\[\]{}/])', r'\\\1', v)


IMAGE_DIRS = ('AI', 'Basic')   # every  <key>=<value>.png  in these folders becomes a rule


def selector(key, value):
    k = key.replace('"', '\\"')
    return f'["{k}"=~/^{regex_escape(value)}$/]'


def main():
    tpl = open(TEMPLATE, encoding='utf-8').read()
    used_by_template = {os.path.normpath(p) for p in re.findall(r'\{\{img:([^}:]+)', tpl)}

    def fill(m):
        return data_uri(os.path.join(ROOT, m.group(1)), int(m.group(2) or PX))
    tpl = re.sub(r'\{\{img:([^}:]+)(?::(\d+))?\}\}', fill, tpl)

    # collect images named <key>=<value>.png  (split at the FIRST "=")
    images, seen = [], set()
    for d in IMAGE_DIRS:
        folder = os.path.join(ROOT, d)
        if not os.path.isdir(folder):
            continue
        for fn in sorted(os.listdir(folder)):
            base, ext = os.path.splitext(fn)
            rel = os.path.normpath(os.path.join(d, fn))
            if ext.lower() not in EXTS or '=' not in base or rel in used_by_template:
                continue
            key, value = base.split('=', 1)
            if not key or not value:
                continue
            if (key, value) in seen:
                print(f'[WARN] duplicate image for {key}={value}: {rel} ignored')
                continue
            seen.add((key, value))
            images.append((key, value, os.path.join(ROOT, rel)))
    others = [i for i in images if i[0] != 'sign_type']
    signs = [i for i in images if i[0] == 'sign_type']

    g = []
    g.append("""/* ============================================================
   GENERATED BY tools/build_hudhud_style.py  -  DO NOT EDIT BY HAND
   To add a sign: upload  <key>=<value>.png  to the AI or Basic folder
   on GitHub (e.g. QC=Done.png, sign_type=highway=stop.png).
   Any node with that tag gets the image. sign_type wins over other tags.
   ============================================================ */

/* Nodes that have a tag with an image (+ any sign_type, for unKnown) */""")
    g.append(',\n'.join(['node[sign_type]'] + [f'node{selector(k, v)}' for k, v, _ in others])
             + ' { set .hz_m; }')
    g.append('\n/* Zoom switches (from Style settings) */')
    # one rule per zoom level: visible when current zoom >= the number in Style settings
    for z, rng in ((14, 'z14'), (15, 'z15'), (16, 'z16'), (17, 'z17'), (18, 'z18-')):
        g.append(f'node|{rng}.hz_m[(setting("icon_zoom") <= {z})] {{ set .hz_icon; }}')
    for z, rng in ((16, 'z16'), (17, 'z17'), (18, 'z18'), (19, 'z19-')):
        g.append(f'node|{rng}.hz_m[setting("show_labels")][(setting("label_zoom") <= {z})] {{ set .hz_label; }}')

    g.append(f"""
/* Size / opacity for every icon; "unKnown" for a sign_type without image */
node.hz_icon {{
    icon-width: eval(setting("icon_size"));
    icon-height: eval(setting("icon_size"));
    icon-opacity: eval(setting("icon_opacity"));
}}
node.hz_icon[sign_type] {{ icon-image: "{data_uri(UNKNOWN)}"; }}

/* One rule per image */""")
    for key, value, path in others + signs:          # sign_type last -> wins
        g.append(f'node.hz_icon{selector(key, value)} {{ icon-image: "{data_uri(path)}"; }}')

    g.append("""
/* Labels */
node.hz_label {
    text-color: setting("label_color");
    text-halo-color: black;
    text-halo-radius: 2;
    text-offset-y: 25;
    font-size: eval(setting("font_size"));
}""")
    for key, value, _ in others:
        kv = f'{key}={value}'.replace('"', '\\"')
        v = value.replace('"', '\\"')
        g.append(f'node.hz_label[!sign_type]{selector(key, value)} {{ text: "{kv}"; }}')
        g.append(f'node.hz_label[!sign_type]{selector(key, value)}[setting("label_short")] {{ text: "{v}"; }}')
    g.append('node.hz_label[sign_type] { text: eval(tag("sign_type")); }')
    g.append('node.hz_label[sign_type][setting("label_short")] { text: eval(any(get(regexp_match("^.*=(.*)$", tag("sign_type")), 1), tag("sign_type"))); }\n')

    out = tpl.replace('/*@@GENERATED_SIGNS@@*/', '\n'.join(g))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    open(OUT, 'w', encoding='utf-8', newline='\n').write(out)
    print(f'{OUT}: {len(images)} images ({len(signs)} sign_type, {len(others)} other tags), {len(out)/1024:.0f} KB')


if __name__ == '__main__':
    main()
